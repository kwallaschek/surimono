# Whether Chromium applies a rule after each of a set of prefixes, in every path of up to
# three wrappers: the data of crates/surimono/src/print/rules.rs's superset test
# (`probe7.tsv` here, Q-PKG-08). Never edit probe7.tsv by hand; run this:
#
#   python3 -I measure.py > probe7.tsv
#
# Chromium is the pinned channel the fixtures use (Playwright, channel "chromium").
import itertools
from playwright.sync_api import sync_playwright

R = ".p{color:rgb(1,2,3)}"
W = {
    "media": "@media all{%s}", "supports": "@supports (color:red){%s}", "layer": "@layer l{%s}",
    "scope": "@scope (html){%s}", "container": "@container (min-width:0px){%s}", "style": "*{%s}",
}
PREFIXES = {'custom-empty': '--x: {}',
    'custom-ident': '--x:foo{}',
    'custom-ws': '--x : {}',
    'custom-semi': '--x: {};',
    'custom-val-semi': '--x: 1;',
    'decl': 'color: red;',
    'decl-block': 'color: red{}',
    'ident-colon-block': 'a:hover{}',
    'custom-then-rule': '--x:{} y{}',
    'x:y;z{}': 'x:y;z{}',
    'semi': ';',
    'important': 'color:red !important;',
    'important-block': '!important{}',
    'close-paren': ')',
    'close-square': ']',
    'close-curly': '}',
    'open-paren-closed': '(a){}',
    'at-unknown-stmt': '@x;',
    'at-unknown-block': '@x{}',
    'cdo': '<!--',
    'custom-nested-block': '--x:{a:b}',
    'custom-nested-rule': '--x:{} --y:{}',
    'bang': '!',
    'colon': ':',
    'nested-decl-like': 'x:{}',
    'url': 'url(x){}',
    'string': "'a'{}", 'number': '1{}',
    'dashdash': '--: {}',
    'dashdash-semi': '--: 1;',
    'dash-ident': '-x: {}',
    'custom-hover': '--x:hover {}',
    'custom-comment': '--/**/x: {}',
    'custom-esc': '\\2d\\2d x: {}',
    'custom-esc2': '-\\-x: {}',
    'decl-then-media': 'color: red; @media all{}',
    'custom-unicode': '--é: {}',
    'custom-nonascii2': '--xé: {}'}
PAGE = ('<!doctype html><html><head><style>body,div{container-type:inline-size}</style><style>%s</style></head>'
        '<body><div><div><div><p class=p>x</p></div></div></div></body></html>')


def wrap(path, inner):
    for w in reversed(path):
        inner = W[w] % inner
    return inner


with sync_playwright() as p:
    b = p.chromium.launch(channel="chromium")
    page = b.new_page()
    page.emulate_media(media="print")

    def applies(css):
        page.set_content(PAGE % css)
        return page.evaluate("getComputedStyle(document.querySelector('.p')).color") == "rgb(1, 2, 3)"

    print("# Chromium %s (Q-PKG-08, probe7): whether R applies after each prefix in each path" % b.version)
    print("# of wrappers. A case is wrap(path, prefix + \" \" + R), wrappers applied outermost first.")
    print("# Generated by measure.py here; never edited by hand.")
    print("rule\t" + R)
    for k, v in W.items():
        print("wrapper\t%s\t%s" % (k, v))
    for k, v in PREFIXES.items():
        print("prefix\t%s\t%s" % (k, v))
    for path in [()] + [q for n in (1, 2, 3) for q in itertools.product(W, repeat=n)]:
        control = applies(wrap(path, R))
        bits = "".join("1" if applies(wrap(path, "%s %s" % (pre, R))) else "0" for pre in PREFIXES.values())
        print("path\t%s\t%d\t%s" % ("/".join(path) or "top", control, bits))
    b.close()

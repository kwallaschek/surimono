#!/usr/bin/env node
// Chrome reference renders for the visual fixtures.
//
//   node reference.mjs --out DIR [--update] [--kind islands] [fixture ...]
//
// For every fixture: Chrome renders the islands client-side with the pinned
// libraries, prints the page to PDF (preferCSSPageSize, printBackground), and
// pdftoppm rasterises it at 96 dpi. Each island's SVG is also printed alone on
// a page of exactly its size (no margin), so islands can be compared without
// the rest of the page. Everything lands in DIR/<fixture>/:
//   chrome.pdf, chrome-<page>.png       the full page
//   island-<i>.svg, island-<i>.png      each island alone (Chrome's own SVG)
//   island-<i>.texts.json               the strings in that SVG, and each <text>'s font
//                                       weight and style (lib/svgtext.mjs)
//   prepass.html                        the source with markers replaced by Chrome's SVG
//   render.json                         versions, fonts, island sizes, console output
//
// Default (check) mode compares the fresh PNGs with the committed
// <fixture>/reference/{chrome-<page>,island-<i>}.png and exits 1 if any changed.
// --update copies the fresh PNGs into <fixture>/reference/ and writes
// reference/reference.toml. Only run --update for a new fixture or after a
// deliberate Chromium or library upgrade, and say so in the pull request.

import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { parseArgs } from "node:util";
import {
  DPI,
  LOCALE,
  TIMEZONE,
  checkInstalledVersions,
  launchChromium,
  listFixtures,
  popplerVersion,
  prepassHtml,
  printIslandInChrome,
  rasterise,
  renderFixtureInChrome,
} from "./lib/fixtures.mjs";
import { referenceFiles } from "./lib/compare.mjs";
import { diff, pixelsIdentical, readPng, sideBySide, writePng } from "./lib/png.mjs";
import { svgTextStyles, svgTexts } from "./lib/svgtext.mjs";

const { values, positionals } = parseArgs({
  allowPositionals: true,
  options: {
    out: { type: "string" },
    update: { type: "boolean", default: false },
    kind: { type: "string", default: "islands" },
  },
});
if (!values.out) {
  console.error("usage: node reference.mjs --out DIR [--update] [--kind islands] [fixture ...]");
  process.exit(2);
}
const outRoot = path.resolve(values.out);
fs.mkdirSync(outRoot, { recursive: true });

const sha256 = (file) => crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex");
const tomlString = (s) => JSON.stringify(String(s));

function referenceToml(env, pages, islands) {
  const lines = [
    "# Chrome reference render. Generated by fixtures/tools/reference.sh --update; never edit by hand.",
    `chromium = ${tomlString(env.chromium)}`,
    `playwright = ${tomlString(env.versions.playwright)}`,
    `poppler = ${tomlString(env.poppler)}`,
    `dpi = ${DPI}`,
    `timezone = ${tomlString(TIMEZONE)}`,
    `locale = ${tomlString(LOCALE)}`,
    `echarts = ${tomlString(env.versions.echarts)}`,
    `vega = ${tomlString(env.versions.vega)}`,
    `vega_lite = ${tomlString(env.versions["vega-lite"])}`,
    `pages = ${pages.length}`,
    "",
  ];
  for (const p of pages) {
    const png = readPng(p);
    lines.push("[[page]]", `file = ${tomlString(path.basename(p))}`, `width = ${png.width}`, `height = ${png.height}`, `sha256 = ${tomlString(sha256(p))}`, "");
  }
  for (const isl of islands) {
    lines.push("[[island]]", `index = ${isl.index}`, `file = ${tomlString(path.basename(isl.png))}`, `width = ${isl.width}`, `height = ${isl.height}`, `renderer = ${tomlString(isl.renderer)}`, `sha256 = ${tomlString(sha256(isl.png))}`, "");
  }
  return lines.join("\n");
}

/** Reads the few scalar keys we need from reference.toml (flat `key = "value"` lines). */
function readReferenceMeta(file) {
  const meta = {};
  for (const line of fs.readFileSync(file, "utf8").split("\n")) {
    const m = /^(\w+)\s*=\s*"?([^"]*)"?\s*$/.exec(line);
    if (m && !(m[1] in meta)) meta[m[1]] = m[2];
  }
  return meta;
}

function compareSet(name, expectedFiles, freshFiles, results) {
  let status = "identical";
  if (expectedFiles.length !== freshFiles.length) {
    results.push({ name, result: "changed", detail: `${freshFiles.length} files, reference has ${expectedFiles.length}` });
    return "changed";
  }
  for (const [i, fresh] of freshFiles.entries()) {
    const expected = readPng(expectedFiles[i]);
    const actual = readPng(fresh);
    const label = `${name}-${i + (name === "page" ? 1 : 0)}`;
    if (pixelsIdentical(expected, actual)) {
      results.push({ name: label, result: "identical" });
      continue;
    }
    const { score, image } = diff(expected, actual);
    // Only anti-aliasing differs (pixelmatch ignores AA pixels): the same render.
    const result = score.size_match && score.diff_pixels === 0 ? "reproduced" : "changed";
    if (result === "changed") {
      status = "changed";
      writePng(path.join(path.dirname(fresh), `check-${label}.png`), sideBySide([expected, actual, image]));
    } else if (status === "identical") {
      status = "reproduced";
    }
    results.push({ name: label, result, ...score });
  }
  return status;
}

/** Fresh island strings against the committed island-<i>.texts.json. */
function compareTextSets(expectedFiles, freshFiles, results) {
  let status = "identical";
  if (expectedFiles.length !== freshFiles.length) {
    results.push({ name: "texts", result: "changed", detail: `${freshFiles.length} files, reference has ${expectedFiles.length}` });
    return "changed";
  }
  for (const [i, fresh] of freshFiles.entries()) {
    const same = fs.readFileSync(expectedFiles[i], "utf8") === fs.readFileSync(fresh, "utf8");
    results.push({ name: `texts-${i}`, result: same ? "identical" : "changed" });
    if (!same) status = "changed";
  }
  return status;
}

function checkFixture(fixture, freshPages, freshIslands, freshTexts, env) {
  const metaFile = path.join(fixture.dir, "reference", "reference.toml");
  if (!fs.existsSync(metaFile)) return { status: "missing", detail: "no committed reference; run reference.sh --update" };
  const meta = readReferenceMeta(metaFile);
  const notes = [];
  if (meta.chromium !== env.chromium) notes.push(`reference made with Chromium ${meta.chromium}, this run uses ${env.chromium}`);
  if (meta.poppler !== env.poppler) notes.push(`reference rasterised with poppler ${meta.poppler}, this run uses ${env.poppler}`);
  const refs = referenceFiles(fixture.dir);
  const results = [];
  const statuses = [compareSet("page", refs.pages, freshPages, results), compareSet("island", refs.islands, freshIslands, results), compareTextSets(refs.texts, freshTexts, results)];
  const status = statuses.includes("changed") ? "changed" : statuses.includes("reproduced") ? "reproduced" : "identical";
  const changed = results.filter((r) => r.result === "changed").map((r) => r.name);
  return { status, detail: changed.length ? `changed: ${changed.join(", ")}` : undefined, results, notes };
}

const env = { versions: checkInstalledVersions(), poppler: popplerVersion() };
const fixtures = listFixtures(values.kind, positionals);
if (!fixtures.length) {
  console.log(`no ${values.kind} fixtures yet`);
  process.exit(0);
}

const browser = await launchChromium();
env.chromium = browser.version();
console.log(`Chromium ${env.chromium}, Playwright ${env.versions.playwright}, poppler ${env.poppler}, ${DPI} dpi`);
const report = { mode: values.update ? "update" : "check", env, fixtures: {} };
let failed = 0;
try {
  for (const fixture of fixtures) {
    const out = path.join(outRoot, fixture.name);
    fs.rmSync(out, { recursive: true, force: true });
    fs.mkdirSync(out, { recursive: true });
    const pdf = path.join(out, "chrome.pdf");
    let rendered;
    try {
      rendered = await renderFixtureInChrome(browser, fixture, pdf);
    } catch (e) {
      failed++;
      report.fixtures[fixture.name] = { status: "error", detail: e.message };
      console.error(`ERROR    ${fixture.name}: ${e.message}`);
      continue;
    }
    const source = fs.readFileSync(path.join(fixture.dir, "input.html"), "utf8");
    fs.writeFileSync(path.join(out, "prepass.html"), prepassHtml(source, rendered.islands.map((i) => i.svg)));
    const pages = rasterise(pdf, out, "chrome");
    const islands = [];
    for (const isl of rendered.islands) {
      const base = path.join(out, `island-${isl.index}`);
      fs.writeFileSync(`${base}.svg`, isl.svg);
      fs.writeFileSync(`${base}.texts.json`, `${JSON.stringify({ ...svgTexts(isl.svg), styles: svgTextStyles(isl.svg) }, null, 1)}\n`);
      await printIslandInChrome(browser, fixture, isl.index, isl.svg, isl.width, isl.height, `${base}.pdf`);
      const [png, ...extra] = rasterise(`${base}.pdf`, out, `.island-${isl.index}`);
      if (extra.length) throw new Error(`${fixture.name}: island ${isl.index} printed on ${extra.length + 1} pages`);
      fs.renameSync(png, `${base}.png`);
      islands.push({ ...isl, png: `${base}.png`, texts: `${base}.texts.json` });
    }
    fs.writeFileSync(
      path.join(out, "render.json"),
      `${JSON.stringify(
        {
          fixture: fixture.name,
          chromium: env.chromium,
          ...env.versions,
          poppler: env.poppler,
          fonts: rendered.fonts,
          islands: rendered.islands.map(({ index, renderer, width, height, svg }) => ({ index, renderer, width, height, svg_bytes: svg.length, svg_sha256: crypto.createHash("sha256").update(svg).digest("hex") })),
          console: rendered.console,
          pages: pages.map((p) => path.basename(p)),
        },
        null,
        2,
      )}\n`,
    );
    if (values.update) {
      const refDir = path.join(fixture.dir, "reference");
      fs.rmSync(refDir, { recursive: true, force: true });
      fs.mkdirSync(refDir, { recursive: true });
      for (const p of [...pages, ...islands.flatMap((i) => [i.png, i.texts])]) fs.copyFileSync(p, path.join(refDir, path.basename(p)));
      fs.writeFileSync(
        path.join(refDir, "reference.toml"),
        referenceToml(
          env,
          pages.map((p) => path.join(refDir, path.basename(p))),
          islands.map((i) => ({ ...i, png: path.join(refDir, path.basename(i.png)) })),
        ),
      );
      report.fixtures[fixture.name] = { status: "updated", pages: pages.length, islands: islands.length };
      console.log(`updated  ${fixture.name} (${pages.length} page${pages.length > 1 ? "s" : ""}, ${islands.length} island${islands.length === 1 ? "" : "s"})`);
    } else {
      const result = checkFixture(
        fixture,
        pages,
        islands.map((i) => i.png),
        islands.map((i) => i.texts),
        env,
      );
      report.fixtures[fixture.name] = result;
      if (result.status === "changed" || result.status === "missing") failed++;
      console.log(`${result.status.padEnd(8)} ${fixture.name}${result.detail ? `: ${result.detail}` : ""}`);
      for (const n of result.notes || []) console.log(`         note: ${n}`);
    }
    if (rendered.console.length) console.log(`         console: ${rendered.console.join(" | ")}`);
  }
} finally {
  await browser.close();
}
fs.writeFileSync(path.join(outRoot, "reference-report.json"), `${JSON.stringify(report, null, 2)}\n`);
console.log(`${fixtures.length - failed}/${fixtures.length} fixtures ok; report: ${path.join(outRoot, "reference-report.json")}`);
process.exit(failed ? 1 : 0);

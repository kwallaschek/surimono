#!/usr/bin/env bash
# Regenerates src/css_properties.rs from w3c/webref's ed/css/ at a given commit.
# Run by hand only (it uses the network); builds and tests never call it. Use the
# commit in crates/webidl/idl/SOURCES.md, so the IDL and the names stay in step.
#
# Usage: crates/dom/fetch-css-properties.sh <webref commit sha>
set -euo pipefail
commit="${1:?usage: fetch-css-properties.sh <webref commit sha>}"
[[ "$commit" =~ ^[0-9a-f]{40}$ ]] || { echo "need a full 40-character commit sha" >&2; exit 2; }
here="$(cd "$(dirname "$0")" && pwd)"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
git -C "$tmp" init -q
git -C "$tmp" remote add origin https://github.com/w3c/webref
git -C "$tmp" fetch -q --depth 1 origin "$commit"
git -C "$tmp" checkout -q FETCH_HEAD
cat > "$tmp/gen.py" <<'PY'
import glob, json, re, sys
commit, root = sys.argv[1:]
names = {}
for path in sorted(glob.glob(root + "/ed/css/*.json")):
    for prop in json.load(open(path, encoding="utf-8")).get("properties", []):
        name = prop["name"]
        if re.fullmatch(r"-?[a-z][a-z0-9-]*", name):
            names.setdefault(name, "")
            names[name] = names[name] or prop.get("legacyAliasOf") or ""
print("// @generated by crates/dom/fetch-css-properties.sh. Do not edit by hand.")
print(f"// Property names in w3c/webref ed/css at {commit} (MIT).")
print()
print("/// `(name, the property it is a legacy alias of, or \"\")`, sorted by name.")
print("#[rustfmt::skip]")
print("pub(crate) const CSS_PROPERTIES: &[(&str, &str)] = &[")
for name in sorted(names):
    print(f'    ("{name}", "{names[name]}"),')
print("];")
PY
python3 -I "$tmp/gen.py" "$commit" "$tmp" > "$here/src/css_properties.rs"

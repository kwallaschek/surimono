#!/usr/bin/env node
// Writes the licence notices of every npm package that went into a bundle.
//
//   node tools/licenses.js <esbuild-metafile.json> <bundle-name>
//
// Reads the bundle's inputs from esbuild's metafile, finds the package each
// input belongs to, and prints one section per package (name, version,
// licence, and the full text of its licence file), sorted by name. The
// output is deterministic, so build.sh --check can compare it.
'use strict';

const fs = require('fs');
const path = require('path');

const [metafile, bundleName] = process.argv.slice(2);
if (!metafile || !bundleName) {
  console.error('usage: node tools/licenses.js <metafile> <bundle-name>');
  process.exit(2);
}
const meta = JSON.parse(fs.readFileSync(metafile, 'utf8'));

// node_modules/a/..., node_modules/@s/a/..., node_modules/a/node_modules/b/...
function packageDir(input) {
  const parts = input.split('/');
  const i = parts.lastIndexOf('node_modules');
  if (i < 0) return null;
  const n = parts[i + 1] && parts[i + 1].startsWith('@') ? 2 : 1;
  return parts.slice(0, i + 1 + n).join('/');
}

const dirs = new Set();
for (const input of Object.keys(meta.inputs)) {
  const dir = packageDir(input);
  if (dir) dirs.add(dir);
}

const LICENSE_FILES = /^(licen[cs]e|copying|notice)(\.(md|txt))?$/i;
const sections = [];
for (const dir of dirs) {
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  const files = fs.readdirSync(dir).filter((f) => LICENSE_FILES.test(f)).sort();
  if (!files.some((f) => /^licen[cs]e/i.test(f))) {
    console.error(`licenses.js: ${pkg.name} ${pkg.version} has no LICENSE file`);
    process.exit(1);
  }
  const texts = files.map((f) => fs.readFileSync(path.join(dir, f), 'utf8').trim());
  sections.push({
    key: `${pkg.name}@${pkg.version}`,
    text: `${pkg.name} ${pkg.version}\nLicence: ${pkg.license}\nSource: https://www.npmjs.com/package/${pkg.name}/v/${pkg.version}\n\n${texts.join('\n\n')}\n`,
  });
}
sections.sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));

const rule = '='.repeat(78);
process.stdout.write(
  `Third-party software in the surimono ${bundleName} bundle (${sections.length} packages)\n` +
  `Generated by crates/islands/js/tools/licenses.js from the esbuild metafile.\n\n` +
  sections.map((s) => `${rule}\n${s.text}`).join('\n'),
);

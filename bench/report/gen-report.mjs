#!/usr/bin/env node
// Generates bench/report/report.html, the reference report of the Grover
// benchmark: a six-page annual business report with six chart islands, one per page, taken
// from the checkpoint-2 fixtures (same specs, same seeded data, same fonts).
//
//   node bench/report/gen-report.mjs            # write report.html
//   node bench/report/gen-report.mjs --check    # exit 1 if the committed file differs
//
// The page template is the fixtures' one (fixtures/tools/gen-islands.mjs): it
// avoids the fulgur 0.40.0 layout gaps listed in docs/COMPAT.md, so both
// engines print the same six pages. Islands use the surimono marker; the
// Grover side renders the same markers client-side with the same libraries
// (bench/tools/bench.py builds that page).

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { fontFaceCss, pinnedVersions } from "../../fixtures/tools/lib/fixtures.mjs";
import { fixtures } from "../../fixtures/tools/defs/islands.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const TARGET = path.join(HERE, "report.html");

/**
 * The fixtures the report is made of, in order, one per page. Every section
 * after the first starts a new page: Chrome moves a chart that doesn't fit to
 * the next page, fulgur 0.40.0 splits it across the break, so a page per chart
 * keeps both engines printing the same six pages.
 */
export const SECTIONS = [
  "echarts-bar-simple-latin",
  "echarts-line-dense-latin",
  "vega-bar-simple-latin",
  "vegalite-scatter-dense-latin",
  "echarts-pie-ja",
  "vegalite-line-ja",
];

const { values } = parseArgs({ options: { check: { type: "boolean", default: false } } });

const round2 = (x) => Math.round(x * 100) / 100;
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const scriptJson = (v) => {
  const pretty = JSON.stringify(v, null, 1);
  return (pretty.length > 30000 ? JSON.stringify(v) : pretty).replace(/</g, "\\u003c").replace(/>/g, "\\u003e").replace(/&/g, "\\u0026");
};

function marker(island) {
  return `<script type="application/vnd.surimono+json" data-renderer="${island.renderer}" data-width="${island.width}" data-height="${island.height}">${scriptJson(island.spec)}</script>`;
}

function table(t) {
  // Fixed-basis flex rows instead of <table> (fulgur 0.40.0 sizes table columns
  // differently from Chrome; see docs/COMPAT.md).
  const n = t.head.length;
  const basis = (i) => (i === 0 ? 40 : round2(60 / (n - 1)));
  const cell = (c, i) => `<span class="c${t.numeric?.[i] ? " num" : ""}" style="flex-basis: ${basis(i)}%">${esc(c)}</span>`;
  const head = `<div class="tr th">${t.head.map((h, i) => cell(h, i)).join("")}</div>`;
  const rows = t.rows.map((r) => `      <div class="tr">${r.map((c, i) => cell(c, i)).join("")}</div>`).join("\n");
  return `    <div class="table">\n      ${head}\n${rows}\n    </div>\n`;
}

/** "Figure 1. Text" / "図1　テキスト" renumbered to n. */
function caption(text, n) {
  return text.replace(/^Figure 1\b/, `Figure ${n}`).replace(/^図1/, `図${n}`).replace(/ \/ 図1/, ` / 図${n}`);
}

function section(f, n) {
  if (f.islands.length !== 1) throw new Error(`${f.name}: the report expects one island per fixture`);
  const isl = f.islands[0];
  const ja = f.lang === "ja";
  return `  <section class="${ja ? "ja" : "en"}" lang="${f.lang}">
    <h2>${esc(f.title)}</h2>
    <p>${esc(f.intro)}</p>
    <figure class="island" style="width: ${isl.width}px; height: ${isl.height}px">
      ${marker(isl)}
    </figure>
    <p class="caption">${esc(caption(isl.caption, n))}</p>
${f.table ? table(f.table) : ""}  </section>`;
}

export function reportHtml() {
  const byName = new Map(fixtures.map((f) => [f.name, f]));
  const versions = pinnedVersions();
  const body = SECTIONS.map((name, i) => {
    const f = byName.get(name);
    if (!f) throw new Error(`no fixture named ${name} in fixtures/tools/defs/islands.mjs`);
    return section(f, i + 1);
  }).join("\n");
  const fontFaces = fontFaceCss("../../fixtures/fonts")
    .split("\n")
    .map((l) => `    ${l}`)
    .join("\n");
  return `<!doctype html>
<!-- Reference report of the Grover benchmark. Generated by bench/report/gen-report.mjs
     from the checkpoint-2 fixtures (${SECTIONS.join(", ")});
     echarts ${versions.echarts}, vega ${versions.vega}, vega-lite ${versions["vega-lite"]}. Edit the generator, not this file. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <title>Annual business report FY2026</title>
  <style>
${fontFaces}
    @page { size: 210mm 297mm; margin: 15mm; }
    html { font-family: "Noto Sans", "Noto Sans JP"; font-size: 13px; line-height: 19px; color: #1f2328; background: #ffffff; text-spacing-trim: space-all; }
    body { margin: 0; }
    /* Same rules as the fixture pages: whole-pixel sizes, no tables, no
       single-side border colours, no auto-sized flex items (docs/COMPAT.md). */
    header { margin-bottom: 16px; }
    header .org { font-weight: 700; font-size: 16px; line-height: 22px; }
    header .meta { font-size: 12px; line-height: 17px; color: #57606a; }
    .rule { height: 2px; background: #1f2328; margin: 8px 0 18px; }
    h1 { font-size: 21px; line-height: 28px; font-weight: 700; margin: 0 0 12px; }
    h2 { font-size: 16px; line-height: 22px; font-weight: 700; margin: 0 0 8px; }
    p { margin: 0 0 12px; }
    section { margin: 0 0 20px; }
    section + section { break-before: page; }
    section.ja { font-family: "Noto Sans JP", "Noto Sans"; }
    figure.island { margin: 12px 0 4px; padding: 0; }
    figure.island svg { display: block; }
    .caption { font-size: 11px; line-height: 16px; color: #57606a; margin-bottom: 12px; }
    .table { font-size: 12px; line-height: 17px; }
    .tr { display: flex; flex-wrap: nowrap; }
    .tr:nth-child(odd) { background: #f6f8fa; }
    .tr.th { font-weight: 700; background: #e8ecf0; }
    .c { flex-grow: 0; flex-shrink: 0; box-sizing: border-box; padding: 4px 8px; text-align: left; white-space: nowrap; overflow: hidden; }
    .num { text-align: right; }
  </style>
</head>
<body>
  <header>
    <div class="org">Northwind Trading GmbH · 株式会社みなと商事</div>
    <div class="meta">Annual business report · Fiscal year 2026 · Group consolidated</div>
    <div class="rule"></div>
  </header>
  <h1>Annual business report FY2026</h1>
  <p>Revenue, orders, receivables and the Japanese subsidiary's figures for the fiscal year. Every chart is drawn from the data in this document when it is printed.</p>
${body}
</body>
</html>
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const html = reportHtml();
  if (values.check) {
    if (!fs.existsSync(TARGET) || fs.readFileSync(TARGET, "utf8") !== html) {
      console.error("bench/report/report.html differs from its generator: run node bench/report/gen-report.mjs");
      process.exit(1);
    }
    console.log("bench/report/report.html matches its generator");
  } else {
    fs.writeFileSync(TARGET, html);
    console.log(`wrote ${path.relative(process.cwd(), TARGET)}`);
  }
}
